    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_artists PRIMARY KEY (user_seq),
    CONSTRAINT fk_artists_user
        FOREIGN KEY (user_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_artists_mod_usr
        FOREIGN KEY (mod_usr_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_artists_verification_processed_usr
        FOREIGN KEY (verification_processed_usr_seq)
        REFERENCES users (user_seq)
        ON DELETE RESTRICT,
    CONSTRAINT ck_artists_verification_status
        CHECK (
            verification_status IN (
                'UNVERIFIED',
                'PENDING',
                'VERIFIED',
                'REJECTED'
            )
        ),
    CONSTRAINT ck_artists_verification_result
        CHECK (
            (
                verification_status = 'VERIFIED'
                AND verification_processed_dttm IS NOT NULL
                AND verification_processed_usr_seq IS NOT NULL
                AND rejection_reason IS NULL
            )
            OR
            (
                verification_status = 'REJECTED'
                AND verification_processed_dttm IS NOT NULL
                AND verification_processed_usr_seq IS NOT NULL
                AND rejection_reason IS NOT NULL
            )
            OR
            (
                verification_status IN ('UNVERIFIED', 'PENDING')
                AND verification_processed_dttm IS NULL
                AND verification_processed_usr_seq IS NULL
                AND rejection_reason IS NULL
            )
        )
);

