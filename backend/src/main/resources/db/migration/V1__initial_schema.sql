CREATE TABLE dm_rooms (
    dm_room_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user1_seq INTEGER NOT NULL,
    user2_seq INTEGER NOT NULL,
    last_message_dttm TIMESTAMPTZ,
    reg_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_dm_rooms PRIMARY KEY (dm_room_seq),
    CONSTRAINT uq_dm_rooms_users UNIQUE (user1_seq, user2_seq),
    CONSTRAINT fk_dm_rooms_user1
        FOREIGN KEY (user1_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_dm_rooms_user2
        FOREIGN KEY (user2_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT ck_dm_rooms_user_order
        CHECK (user1_seq < user2_seq)
);

CREATE TABLE dm_room_participants (
    dm_room_seq BIGINT NOT NULL,
    user_seq INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_notification_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_hidden_message_seq BIGINT,
    last_left_dttm TIMESTAMPTZ,

    CONSTRAINT pk_dm_room_participants PRIMARY KEY (dm_room_seq, user_seq),
    CONSTRAINT fk_dm_room_participants_room
        FOREIGN KEY (dm_room_seq)
        REFERENCES dm_rooms (dm_room_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_dm_room_participants_user
        FOREIGN KEY (user_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT ck_dm_room_participants_left
        CHECK (is_active = TRUE OR last_left_dttm IS NOT NULL)
);

CREATE TABLE dm_messages (
    dm_message_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    dm_room_seq BIGINT NOT NULL,
    sender_seq INTEGER NOT NULL,
    message_type VARCHAR(20) NOT NULL,
    text_content VARCHAR(4000),
    image_seq BIGINT,
    read_dttm TIMESTAMPTZ,
    reg_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq INTEGER NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_dm_messages PRIMARY KEY (dm_message_seq),
    CONSTRAINT uq_dm_messages_room_message
        UNIQUE (dm_room_seq, dm_message_seq),
    CONSTRAINT fk_dm_messages_room
        FOREIGN KEY (dm_room_seq)
        REFERENCES dm_rooms (dm_room_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_dm_messages_sender
        FOREIGN KEY (dm_room_seq, sender_seq)
        REFERENCES dm_room_participants (dm_room_seq, user_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_dm_messages_image
        FOREIGN KEY (image_seq) REFERENCES images (image_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_dm_messages_mod_usr
        FOREIGN KEY (mod_usr_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT ck_dm_messages_type
        CHECK (message_type IN ('TEXT', 'IMAGE', 'TEXT_WITH_IMAGE')),
    CONSTRAINT ck_dm_messages_content
        CHECK (
            (
                message_type = 'TEXT'
                AND text_content IS NOT NULL
                AND image_seq IS NULL
            )
            OR
            (
                message_type = 'IMAGE'
                AND text_content IS NULL
                AND image_seq IS NOT NULL
            )
            OR
            (
                message_type = 'TEXT_WITH_IMAGE'
                AND text_content IS NOT NULL
                AND image_seq IS NOT NULL
            )
        ),
    CONSTRAINT ck_dm_messages_deleted_modifier
        CHECK (
            (is_deleted = FALSE AND mod_usr_seq = sender_seq)
            OR
            (is_deleted = TRUE AND mod_usr_seq IS NOT NULL)
        )
);

ALTER TABLE dm_room_participants
    ADD CONSTRAINT fk_dm_room_participants_last_hidden_message
    FOREIGN KEY (dm_room_seq, last_hidden_message_seq)
    REFERENCES dm_messages (dm_room_seq, dm_message_seq)
    ON DELETE RESTRICT;

