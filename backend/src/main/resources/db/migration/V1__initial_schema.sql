            rendering_style_1_seq IS NULL
            OR rendering_style_2_seq IS NULL
            OR rendering_style_1_seq <> rendering_style_2_seq
        ),
    CONSTRAINT ck_tattoos_training
        CHECK (
            (is_used_for_training = TRUE AND trained_dttm IS NOT NULL)
            OR
            (is_used_for_training = FALSE AND trained_dttm IS NULL)
        )
);

