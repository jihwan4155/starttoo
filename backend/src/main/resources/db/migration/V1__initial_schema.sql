    image_seq BIGINT NOT NULL,
    source_type VARCHAR(20) NOT NULL,
    primary_style_seq INTEGER NOT NULL,
    secondary_style_1_seq INTEGER,
    secondary_style_2_seq INTEGER,
    rendering_style_1_seq INTEGER,
    rendering_style_2_seq INTEGER,
    color_seq INTEGER,
    is_used_for_training BOOLEAN NOT NULL DEFAULT FALSE,
    trained_dttm TIMESTAMPTZ,
    reg_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_tattoos PRIMARY KEY (tattoo_seq),
    CONSTRAINT uq_tattoos_image UNIQUE (image_seq),
    CONSTRAINT fk_tattoos_registrant
        FOREIGN KEY (registrant_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_tattoos_image
        FOREIGN KEY (image_seq) REFERENCES images (image_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_tattoos_primary_style
        FOREIGN KEY (primary_style_seq)
        REFERENCES primary_styles (primary_style_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_tattoos_secondary_style_1
        FOREIGN KEY (secondary_style_1_seq)
        REFERENCES secondary_styles (secondary_style_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_tattoos_secondary_style_2
        FOREIGN KEY (secondary_style_2_seq)
        REFERENCES secondary_styles (secondary_style_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_tattoos_rendering_style_1
        FOREIGN KEY (rendering_style_1_seq)
        REFERENCES rendering_styles (rendering_style_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_tattoos_rendering_style_2
        FOREIGN KEY (rendering_style_2_seq)
        REFERENCES rendering_styles (rendering_style_seq)
        ON DELETE RESTRICT,
    CONSTRAINT fk_tattoos_color
        FOREIGN KEY (color_seq) REFERENCES colors (color_seq) ON DELETE RESTRICT,
    CONSTRAINT ck_tattoos_source_type
        CHECK (source_type IN ('DEFAULT', 'USER_POST', 'USER_COLLECTION')),
