    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_refresh_tokens_device
        FOREIGN KEY (device_seq)
        REFERENCES user_devices (device_seq)
        ON DELETE RESTRICT,
    CONSTRAINT ck_refresh_tokens_hash_length
        CHECK (octet_length(token_hash) = 32),
    CONSTRAINT ck_refresh_tokens_expiry
        CHECK (expires_dttm > reg_dttm)
);

CREATE TABLE notifications (
    notification_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    receiver_seq INTEGER NOT NULL,
    actor_seq INTEGER,
    notification_type VARCHAR(20) NOT NULL,
    reference_seq BIGINT,
    title VARCHAR(100) NOT NULL,
    body VARCHAR(500) NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    read_dttm TIMESTAMPTZ,
    reg_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_notifications PRIMARY KEY (notification_seq),
    CONSTRAINT fk_notifications_receiver
        FOREIGN KEY (receiver_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_actor
        FOREIGN KEY (actor_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT ck_notifications_type
        CHECK (
            notification_type IN (
                'POST_LIKE',
                'POST_COMMENT',
                'COMMENT_LIKE',
                'FOLLOW',
                'SYSTEM'
            )
        ),
    CONSTRAINT ck_notifications_actor_reference
        CHECK (
            (
                notification_type IN (
                    'POST_LIKE',
                    'POST_COMMENT',
                    'COMMENT_LIKE',
                    'FOLLOW'
                )
                AND actor_seq IS NOT NULL
                AND reference_seq IS NOT NULL
            )
            OR
            (
                notification_type = 'SYSTEM'
                AND actor_seq IS NULL
            )
        ),
    CONSTRAINT ck_notifications_read
        CHECK (
            (is_read = TRUE AND read_dttm IS NOT NULL)
            OR
            (is_read = FALSE AND read_dttm IS NULL)
        )
);


