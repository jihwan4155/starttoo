-- Starttoo initial PostgreSQL schema.
-- Flyway가 빈 데이터베이스에 한 번 적용하는 생성 전용 마이그레이션이다.
--
-- pgvector 기능은 현재 비활성화되어 있다.
-- 사용을 시작할 때 확장, tattoo_embeddings 테이블, 벡터 인덱스의 주석을 해제한다.
-- CREATE EXTENSION IF NOT EXISTS vector;
--
-- tattoo_embeddings.embedding의 512차원은 임시값이다.
-- 실제 임베딩 모델을 확정한 뒤 VECTOR(512)를 해당 차원으로 변경한다.


-- =========================================================
-- 1. 회원·공통 이미지
-- users와 images의 순환 FK 중 profile_image_seq는 마지막에 연결한다.
-- =========================================================

CREATE TABLE users (
    user_seq INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nickname VARCHAR(20) NOT NULL,
    phone_number VARCHAR(16) NOT NULL,
    phone_verified_dttm TIMESTAMPTZ NOT NULL,
    profile_image_seq BIGINT,
    birth_date DATE,
    gender CHAR(1),
    role VARCHAR(10) NOT NULL DEFAULT 'USER',
    recent_search_terms VARCHAR(100)[] NOT NULL DEFAULT ARRAY[]::VARCHAR(100)[],
    account_status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE',
    status_changed_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reg_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq INTEGER,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_users PRIMARY KEY (user_seq),
    CONSTRAINT fk_users_mod_usr
        FOREIGN KEY (mod_usr_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT ck_users_nickname_length
        CHECK (char_length(nickname) BETWEEN 2 AND 20),
    CONSTRAINT ck_users_nickname_format
        CHECK (nickname ~ '^[가-힣A-Za-z0-9]+$'),
    CONSTRAINT ck_users_phone_number
        CHECK (phone_number ~ '^\+[1-9][0-9]{7,14}$'),
    CONSTRAINT ck_users_gender
        CHECK (gender IS NULL OR gender IN ('M', 'F')),
    CONSTRAINT ck_users_role
        CHECK (role IN ('USER', 'ARTIST', 'ADMIN')),
    CONSTRAINT ck_users_recent_search_terms
        CHECK (cardinality(recent_search_terms) <= 10),
    CONSTRAINT ck_users_account_status
        CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'BANNED', 'WITHDRAWN'))
);

CREATE TABLE images (
    image_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    object_key VARCHAR(512) NOT NULL,
    reg_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reg_usr_seq INTEGER NOT NULL,
    mod_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mod_usr_seq INTEGER NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_images PRIMARY KEY (image_seq),
    CONSTRAINT uq_images_object_key UNIQUE (object_key),
    CONSTRAINT fk_images_reg_usr
        FOREIGN KEY (reg_usr_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_images_mod_usr
        FOREIGN KEY (mod_usr_seq) REFERENCES users (user_seq) ON DELETE RESTRICT
);

ALTER TABLE users
    ADD CONSTRAINT fk_users_profile_image
    FOREIGN KEY (profile_image_seq)
    REFERENCES images (image_seq)
    ON DELETE RESTRICT;


