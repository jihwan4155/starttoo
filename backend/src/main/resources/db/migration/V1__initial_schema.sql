CREATE TABLE user_account_status_histories (
    account_status_history_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_seq INTEGER NOT NULL,
    previous_status VARCHAR(12),
    changed_status VARCHAR(12) NOT NULL,
    reason_type VARCHAR(20) NOT NULL,
    reason_detail VARCHAR(1000),
    expired_dttm TIMESTAMPTZ,
    reg_dttm TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reg_usr_seq INTEGER,

    CONSTRAINT pk_user_account_status_histories
        PRIMARY KEY (account_status_history_seq),
    CONSTRAINT fk_account_status_histories_user
        FOREIGN KEY (user_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT fk_account_status_histories_reg_usr
        FOREIGN KEY (reg_usr_seq) REFERENCES users (user_seq) ON DELETE RESTRICT,
    CONSTRAINT ck_account_histories_previous_status
        CHECK (
            previous_status IS NULL
            OR previous_status IN ('ACTIVE', 'SUSPENDED', 'BANNED', 'WITHDRAWN')
        ),
    CONSTRAINT ck_account_histories_changed_status
        CHECK (changed_status IN ('ACTIVE', 'SUSPENDED', 'BANNED', 'WITHDRAWN')),
    CONSTRAINT ck_account_histories_reason_type
        CHECK (
            reason_type IN (
                'SIGNUP',
                'USER_REQUEST',
                'POLICY_VIOLATION',
                'ADMIN_ACTION',
                'SUSPENSION_EXPIRED'
            )
        ),
    CONSTRAINT ck_account_histories_signup
        CHECK (
            (
                reason_type = 'SIGNUP'
                AND previous_status IS NULL
                AND changed_status = 'ACTIVE'
                AND reg_usr_seq IS NOT NULL
            )
            OR
            (
                reason_type <> 'SIGNUP'
                AND previous_status IS NOT NULL
            )
        ),
    CONSTRAINT ck_account_histories_actor
        CHECK (
            (
                reason_type = 'SUSPENSION_EXPIRED'
                AND changed_status = 'ACTIVE'
                AND reg_usr_seq IS NULL
            )
            OR
            (
                reason_type <> 'SUSPENSION_EXPIRED'
                AND reg_usr_seq IS NOT NULL
            )
        ),
    CONSTRAINT ck_account_histories_expiry
        CHECK (
            (
                changed_status = 'SUSPENDED'
                AND expired_dttm IS NOT NULL
            )
            OR
            (
                changed_status <> 'SUSPENDED'
                AND expired_dttm IS NULL
            )
        )
);

